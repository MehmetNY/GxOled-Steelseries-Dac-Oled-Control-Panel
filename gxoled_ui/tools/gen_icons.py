#!/usr/bin/env python3
"""Regenerate src/icons_data.rs from a lucide-static checkout.

    npm pack lucide-static && tar xzf lucide-static-*.tgz
    python3 tools/gen_icons.py package/icons > src/icons_data.rs

Lucide is ISC licensed; see licenses/LUCIDE-ISC.txt.
"""
import re, sys, pathlib

NAMES = """settings clock play image monitor music info log-out layout-dashboard globe sun moon power
circle-x zap panel-left scan layers check coffee heart external-link qr-code pencil square-pen plus
trash-2 upload download square sparkles film folder-plus sun-medium shield move wifi plug volume-2 bell
chevron-right chevron-down refresh-cw timer watch calendar-clock file-json file-up file-down save
rotate-ccw wand-sparkles list-music layout-grid cpu hard-drive gauge badge-check circle-check
git-branch code-xml circle-play circle-stop app-window sliders-horizontal shield-check headphones
hourglass unplug clock-3 monitor-play layout-template layout-panel-top heart-handshake image-play""".split()

root = pathlib.Path(sys.argv[1])
print("// @generated by tools/gen_icons.py from lucide-static (ISC license, see licenses/LUCIDE-ISC.txt)")
print("// Inner SVG markup of each 24x24 icon; stroke attributes are applied by the caller.")
print("pub fn svg_inner(name: &str) -> Option<&'static str> {\n    Some(match name {")
for n in NAMES:
    p = root / f"{n}.svg"
    if not p.exists():
        print(f"// missing: {n}"); continue
    s = p.read_text(encoding="utf-8")
    inner = re.search(r"<svg[^>]*>(.*)</svg>", s, re.S).group(1)
    inner = re.sub(r"\s+", " ", inner.strip()).replace('" />', '"/>')
    print(f'        "{n}" => r##"{inner}"##,')
print("        _ => return None,\n    })\n}")
